html.append('function addMessage(role, content, sources) {')
html.append('  if (welcomeScreen) welcomeScreen.style.display = "none";')
html.append('  var div = document.createElement("div");')
html.append('  div.className = "message " + role;')
html.append('  var html = content.replace(/\\n/g, "<br>");')
html.append('  if (sources && sources.length > 0) {')
