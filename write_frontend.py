html.append('  questionInput.value = "";')
html.append('  addMessage("user", question);')
html.append('  sendBtn.disabled = true;')
html.append('  sendBtn.textContent = "发送中...";')
html.append('  addLoading();')
html.append('  try {')
html.append('    var resp = await fetch(API_BASE + "/ask", {')
html.append('      method: "POST",')
html.append('      headers: {"Content-Type": "application/json"},')
html.append('      body: JSON.stringify({question: question})')
html.append('    });')
html.append('    removeLoading();')
html.append('    if (!resp.ok) {')
html.append('      var err = await resp.json();')
html.append('      addMessage("assistant", "\\u274c " + (err.detail || "请求失败"));')
html.append('      return;')
html.append('    }')
html.append('    var data = await resp.json();')
html.append('    addMessage("assistant", data.answer, data.sources);')
html.append('  } catch(e) {')
html.append('    removeLoading();')
html.append('    addMessage("assistant", "\\u274c 无法连接到 API 服务，请确认服务已启动");')
html.append('  }')
html.append('  sendBtn.disabled = false;')
html.append('  sendBtn.textContent = "发送";')
html.append('}')
